import React, { useState, useEffect } from 'react';
import { apiClient } from '../../api/client';
import { useAuth } from '../../context/AuthContext';
import { useToast } from '../../context/ToastContext';
import { useLanguage } from '../../context/LanguageContext';
import { User, Save, ShieldCheck, Sparkles, Phone, Mail, CreditCard } from 'lucide-react';

export const PatientProfile: React.FC = () => {
  const { user, refreshUser } = useAuth();
  const { success, error } = useToast();
  const { lang, t, localizeName } = useLanguage();

  const [fullName, setFullName] = useState(user?.fullName || '');
  const [phone, setPhone] = useState(user?.phone || '');
  const [email, setEmail] = useState('');
  const [age, setAge] = useState<string>('');
  const [gender, setGender] = useState<string>('Female');
  const [abhaId, setAbhaId] = useState<string>('');
  const [aadhar, setAadhar] = useState<string>('');
  const [address, setAddress] = useState<string>('');
  const [loading, setLoading] = useState(false);

  // Check if current user has an auto-generated internal email
  const isAutoGeneratedEmail = user?.email && user.email.endsWith('@medislot.local');

  useEffect(() => {
    async function loadProfile() {
      try {
        const res = await apiClient.get('/patients/me');
        if (res.data && res.data.profile) {
          const p = res.data.profile;
          if (p.fullName) setFullName(p.fullName);
          if (p.phone) setPhone(p.phone);
          if (p.age) setAge(String(p.age));
          if (p.gender) setGender(p.gender);
          if (p.abhaId) setAbhaId(p.abhaId);
          if (p.aadhar) setAadhar(p.aadhar);
          if (p.address) setAddress(p.address);
        }
        if (res.data && res.data.email && !res.data.email.endsWith('@medislot.local')) {
          setEmail(res.data.email);
        } else if (user?.email && !user.email.endsWith('@medislot.local')) {
          setEmail(user.email);
        }
      } catch (err) {
        console.error('Failed to load profile:', err);
      }
    }
    loadProfile();
  }, [user]);

  const handleSave = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    try {
      await apiClient.patch('/patients/me', {
        fullName: fullName.trim(),
        phone: phone.replace(/\D/g, '').slice(-10),
        email: email.trim() ? email.trim().toLowerCase() : undefined,
        age: age ? parseInt(age, 10) : undefined,
        gender,
        abhaId: abhaId.trim(),
        aadhar: aadhar.replace(/\D/g, ''),
        address: address.trim()
      });
      await refreshUser();
      success(lang === 'te' ? 'రోగి ప్రొఫైల్ విజయవంతంగా నవీకరించబడింది.' : 'Patient profile updated successfully.');
    } catch (err: any) {
      error(err.response?.data?.error || (lang === 'te' ? 'ప్రొఫైల్ నవీకరించడం విఫలమైంది.' : 'Failed to update profile.'));
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="main-content" style={{ maxWidth: '680px', padding: '24px 16px' }}>
      <div className="section-header" style={{ marginBottom: '24px' }}>
        <h1 className="section-title">
          {lang === 'te' ? 'రోగి ప్రొఫైల్ & ఆరోగ్య గుర్తింపు సంఖ్య' : 'Patient Profile & Health ID'}
        </h1>
        <p className="section-subtitle">
          {lang === 'te'
            ? 'మీ వ్యక్తిగత వివరాలు, ఆభా ఆరోగ్య గుర్తింపు మరియు చిరునామాను నిర్వహించండి.'
            : 'Manage your personal details, ABHA identification, and contact information.'}
        </p>
      </div>

      <div className="med-card" style={{ padding: '32px' }}>
        <form onSubmit={handleSave} noValidate>
          {/* Full Name */}
          <div className="form-group">
            <label className="form-label" style={{ fontWeight: 700 }}>
              {lang === 'te' ? 'పూర్తి పేరు *' : 'Full Name *'}
            </label>
            <input
              type="text"
              className="form-input"
              required
              value={fullName}
              onChange={(e) => setFullName(e.target.value)}
            />
            {fullName.trim() && (
              <span style={{ fontSize: '0.78rem', color: 'var(--blue-600)', marginTop: '4px', display: 'flex', alignItems: 'center', gap: '4px' }}>
                <Sparkles size={12} />
                <span>{t.autoTeluguPreview} <strong>{localizeName(fullName)}</strong></span>
              </span>
            )}
          </div>

          {/* Primary Account Identity & Contact Row */}
          <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '16px' }}>
            <div className="form-group">
              <label className="form-label" style={{ fontWeight: 700 }}>
                {lang === 'te' ? 'నమోదిత మొబైల్ సంఖ్య (ప్రాథమిక ఖాతా) *' : 'Registered Mobile (Primary Account) *'}
              </label>
              <div style={{ position: 'relative' }}>
                <input
                  type="tel"
                  className="form-input"
                  required
                  maxLength={10}
                  value={phone}
                  onChange={(e) => setPhone(e.target.value.replace(/\D/g, '').slice(0, 10))}
                  style={{ fontWeight: 600 }}
                />
              </div>
              <span style={{ fontSize: '0.72rem', color: 'var(--slate-500)', marginTop: '4px', display: 'block' }}>
                {lang === 'te' ? '💡 మీ 6 అంకెల ఎంపిన్ లాగిన్‌కు ఉపయోగించే సంఖ్య' : '💡 Used for your 6-digit MPIN sign-in'}
              </span>
            </div>

            <div className="form-group">
              <label className="form-label" style={{ fontWeight: 600 }}>
                {lang === 'te' ? 'ఇమెయిల్ చిరునామా (ఐచ్ఛికం)' : 'Email Address (Optional)'}
              </label>
              <input
                type="email"
                className="form-input"
                placeholder={isAutoGeneratedEmail ? (lang === 'te' ? 'నోటిఫికేషన్‌ల కోసం ఇమెయిల్ జోడించండి' : 'Add email for OPD alerts') : 'name@example.com'}
                value={email}
                onChange={(e) => setEmail(e.target.value)}
              />
              <span style={{ fontSize: '0.72rem', color: 'var(--slate-500)', marginTop: '4px', display: 'block' }}>
                {lang === 'te' ? 'ఓపీడీ డిజిటల్ స్లిప్ నోటిఫికేషన్ల కోసం' : 'For OPD appointment slips & notifications'}
              </span>
            </div>
          </div>

          {/* Age & Gender Row */}
          <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '16px' }}>
            <div className="form-group">
              <label className="form-label" style={{ fontWeight: 600 }}>
                {lang === 'te' ? 'వయస్సు (సంవత్సరాలు)' : 'Age (Years)'}
              </label>
              <input
                type="number"
                min="0"
                max="125"
                className="form-input"
                value={age}
                onChange={(e) => setAge(e.target.value)}
              />
            </div>

            <div className="form-group">
              <label className="form-label" style={{ fontWeight: 600 }}>
                {lang === 'te' ? 'లింగం' : 'Gender'}
              </label>
              <select className="form-select" value={gender} onChange={(e) => setGender(e.target.value)}>
                <option value="Female">{lang === 'te' ? 'స్త్రీ' : 'Female'}</option>
                <option value="Male">{lang === 'te' ? 'పురుషుడు' : 'Male'}</option>
                <option value="Other">{lang === 'te' ? 'ఇతర' : 'Other'}</option>
              </select>
            </div>
          </div>

          {/* Dr. NTR Vaidya Seva / ABHA Health ID */}
          <div className="form-group">
            <label className="form-label" style={{ fontWeight: 600 }}>
              {lang === 'te' ? 'డా. ఎన్టీఆర్ వైద్య సేవ / ఆభా హెల్త్ ఐడీ' : 'Dr. NTR Vaidya Seva / ABHA Health ID'}
            </label>
            <input
              type="text"
              className="form-input"
              placeholder={lang === 'te' ? 'ఉదా: NTRVAIDYA-AP-9821443 లేదా ఆభా సంఖ్య' : 'e.g. NTRVAIDYA-AP-9821443 or ABHA number'}
              value={abhaId}
              onChange={(e) => setAbhaId(e.target.value)}
            />
            <span style={{ fontSize: '0.72rem', color: 'var(--slate-500)', marginTop: '4px', display: 'block' }}>
              {lang === 'te'
                ? 'డా. ఎన్టీఆర్ వైద్య సేవ ట్రస్ట్ కింద ఉచిత సేవలు పొందడానికి మీ కార్డు సంఖ్యను నమోదు చేయండి'
                : 'Enter your scheme card number to access Dr. NTR Vaidya Seva free hospital benefits'}
            </span>
          </div>

          {/* Aadhaar Number */}
          <div className="form-group">
            <label className="form-label" style={{ fontWeight: 600 }}>
              {lang === 'te' ? 'ఆధార్ సంఖ్య (12 అంకెలు)' : 'Aadhaar Number (12 digits)'}
            </label>
            <input
              type="text"
              inputMode="numeric"
              className="form-input"
              maxLength={12}
              placeholder="567890123456"
              value={aadhar}
              onChange={(e) => setAadhar(e.target.value.replace(/\D/g, '').slice(0, 12))}
            />
            <div style={{ fontSize: '0.74rem', color: 'var(--slate-500)', marginTop: '4px' }}>
              {lang === 'te'
                ? '💡 మీ 12 అంకెల ఆధార్ నంబర్‌తో కూడా త్వరిత లాగిన్ చేయవచ్చు.'
                : '💡 Enables quick sign-in using your 12-digit Aadhaar number.'}
            </div>
          </div>

          {/* Residential Address */}
          <div className="form-group">
            <label className="form-label" style={{ fontWeight: 600 }}>
              {lang === 'te' ? 'నివాస చిరునామా' : 'Residential Address'}
            </label>
            <textarea
              className="form-textarea"
              rows={2}
              placeholder={lang === 'te' ? 'డోర్ నం, వీధి, గ్రామం/పట్టణం, జిల్లా' : 'Door No, Street, Village/Town, District'}
              value={address}
              onChange={(e) => setAddress(e.target.value)}
            />
          </div>

          <button
            type="submit"
            className="btn btn-primary"
            disabled={loading}
            style={{ width: '100%', height: '46px', marginTop: '12px', fontWeight: 700 }}
          >
            <Save size={16} />
            {loading ? (lang === 'te' ? 'సేవ్ చేస్తోంది...' : 'Saving...') : (lang === 'te' ? 'ప్రొఫైల్ మార్పులను సేవ్ చేయండి' : 'Save Profile Changes')}
          </button>
        </form>
      </div>
    </div>
  );
};
export default PatientProfile;
